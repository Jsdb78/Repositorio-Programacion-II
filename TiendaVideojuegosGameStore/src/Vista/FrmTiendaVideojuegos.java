    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
    String titulo = txtTitulo.getText().trim();
    String precioTexto = txtPrecio.getText().trim();

    if (titulo.isEmpty() || precioTexto.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Debe ingresar el título y el precio base del videojuego.",
                "Campos incompletos",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    double precioBase;
    try {
        precioBase = Double.parseDouble(precioTexto);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(
                this,
                "El precio base debe ser un número válido (ej. 59.99).",
                "Precio inválido",
                JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    if (precioBase <= 0) {
        JOptionPane.showMessageDialog(
                this,
                "El precio base debe ser mayor que cero.",
                "Precio no válido",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String genero = cbxGenero.getSelectedItem().toString();
    boolean incluyeDLC = chkDLC.isSelected();
    boolean esEdicionEspecial = chkEspecial.isSelected();

    Videojuego juego;
    if (rbtFisico.isSelected()) {
        juego = new JuegoFisico(titulo, genero, precioBase, incluyeDLC, esEdicionEspecial, 8.50);
    } else {
        juego = new JuegoDigital(titulo, genero, precioBase, incluyeDLC, esEdicionEspecial, 0.10);
    }

    txtResumen.setText(juego.generarFicha());
    lblEstado.setText("Cotización generada para: " + juego.getTitulo());
    }//GEN-LAST:event_btnRegistrarActionPerformed

