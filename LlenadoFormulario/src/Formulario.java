    private void TogBloqueoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TogBloqueoActionPerformed
        // TODO add your handling code here:
        Color valorInicio = Color.BLUE;
        Color valorFinal = Color.GREEN;
        
        if(TogBloqueo.isSelected()){
            TogBloqueo.setBackground(valorFinal);
            tbnombre.setEnabled(false);
            tbapellido.setEnabled(false);
        }
        else{
            TogBloqueo.setBackground(valorInicio);
            tbnombre.setEnabled(true);
            tbapellido.setEnabled(true);
        }
    }//GEN-LAST:event_TogBloqueoActionPerformed

